using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

public partial class Generate
{
    /// <summary>
    /// Synthetic path used to make Kiota generate the WebSocket message models.
    /// The generated request builder is removed after generation.
    /// </summary>
    const string WebSocketModelsPath = "JellyfinSdkWebSocketModels";

    const string InboundWebSocketMessage = "InboundWebSocketMessage";

    const string OutboundWebSocketMessage = "OutboundWebSocketMessage";

    static string PatchWebSocketSpecification(string specification)
    {
        var document = JsonNode.Parse(specification)!.AsObject();
        var schemas = document["components"]!["schemas"]!.AsObject();

        // Each message inlines the full SessionMessageType enum next to the allOf reference,
        // which makes Kiota generate a separate enum per message. Use the shared enum instead.
        foreach (var (_, schema) in schemas)
        {
            if (schema?["properties"]?["MessageType"] is JsonObject messageType
                && messageType.ContainsKey("allOf"))
            {
                messageType.Remove("enum");
            }
        }

        document["paths"]!.AsObject()[$"/{WebSocketModelsPath}"] = new JsonObject
        {
            ["post"] = new JsonObject
            {
                ["operationId"] = WebSocketModelsPath,
                ["requestBody"] = CreateContent(InboundWebSocketMessage),
                ["responses"] = new JsonObject
                {
                    ["200"] = CreateContent(OutboundWebSocketMessage, "Success")
                }
            }
        };

        return document.ToJsonString();

        static JsonObject CreateContent(string schemaName, string description = null)
        {
            var content = new JsonObject
            {
                ["content"] = new JsonObject
                {
                    ["application/json"] = new JsonObject
                    {
                        ["schema"] = new JsonObject { ["$ref"] = $"#/components/schemas/{schemaName}" }
                    }
                }
            };

            if (description is not null)
            {
                content["description"] = description;
            }

            return content;
        }
    }

    void RemoveWebSocketRequestBuilder()
    {
        Directory.Delete(GeneratedDirectory / WebSocketModelsPath, recursive: true);

        var clientPath = GeneratedDirectory / "BaseJellyfinApiClient.cs";
        var client = File.ReadAllText(clientPath);
        client = WebSocketModelsUsingRegex().Replace(client, string.Empty);
        client = WebSocketModelsPropertyRegex().Replace(client, string.Empty);

        if (client.Contains(WebSocketModelsPath, StringComparison.Ordinal))
        {
            throw new InvalidOperationException($"Unable to remove the {WebSocketModelsPath} request builder from {clientPath}");
        }

        File.WriteAllText(clientPath, client);
    }

    void WriteWebSocketMessages()
    {
        var document = JsonNode.Parse(File.ReadAllText(SpecificationPath))!;
        var mapping = document["components"]!["schemas"]![OutboundWebSocketMessage]!["discriminator"]!["mapping"]!.AsObject();

        var messages = mapping
            .Select(m => (MessageType: m.Key, Model: m.Value!.GetValue<string>().Split('/').Last()))
            .OrderBy(m => m.Model, StringComparer.Ordinal)
            .ToList();

        foreach (var (messageType, model) in messages)
        {
            if (!IdentifierRegex().IsMatch(messageType) || !IdentifierRegex().IsMatch(model))
            {
                throw new InvalidOperationException($"Unsupported WebSocket message mapping {messageType} -> {model}");
            }

            if (!File.Exists(GeneratedDirectory / "Models" / $"{model}.cs"))
            {
                throw new InvalidOperationException($"WebSocket message model {model} was not generated");
            }
        }

        var builder = new StringBuilder();
        builder.Append("""
                       // <auto-generated/>
                       #nullable enable
                       using Microsoft.Kiota.Abstractions.Serialization;
                       namespace Jellyfin.Sdk.Generated.Models
                       {

                       """);

        foreach (var (_, model) in messages)
        {
            builder.Append($$"""
                                 public partial class {{model}} : global::Jellyfin.Sdk.WebSockets.IOutboundWebSocketMessage
                                 {
                                 }

                             """);
        }

        builder.Append("""
                       }
                       namespace Jellyfin.Sdk.Generated
                       {
                           internal static class OutboundWebSocketMessageFactory
                           {
                               internal static ParsableFactory<global::Jellyfin.Sdk.WebSockets.IOutboundWebSocketMessage>? Get(global::Jellyfin.Sdk.Generated.Models.SessionMessageType messageType)
                                   => messageType switch
                                   {

                       """);

        foreach (var (messageType, model) in messages)
        {
            builder.Append($"""
                                            global::Jellyfin.Sdk.Generated.Models.SessionMessageType.{messageType} => global::Jellyfin.Sdk.Generated.Models.{model}.CreateFromDiscriminatorValue,

                            """);
        }

        builder.Append("""
                                       _ => null
                                   };
                           }
                       }

                       """);

        File.WriteAllText(GeneratedDirectory / "WebSocketMessages.cs", builder.ToString().ReplaceLineEndings("\n"));
    }

    [GeneratedRegex($@"^using Jellyfin\.Sdk\.Generated\.{WebSocketModelsPath};\r?\n", RegexOptions.Multiline)]
    private static partial Regex WebSocketModelsUsingRegex();

    [GeneratedRegex($@"^[ \t]*/// <summary>[^\n]*</summary>\r?\n[ \t]*public global::Jellyfin\.Sdk\.Generated\.{WebSocketModelsPath}\.\w+ \w+\r?\n[ \t]*\{{[^}}]*\}}\r?\n", RegexOptions.Multiline)]
    private static partial Regex WebSocketModelsPropertyRegex();

    [GeneratedRegex("^[A-Za-z][A-Za-z0-9]*$")]
    private static partial Regex IdentifierRegex();
}
