using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Jellyfin.Sdk.SourceGenerators;

/// <summary>
/// Implements Jellyfin.Sdk.Internal.IFieldAssignable by copying each GetFieldDeserializers lambda body into a switch case.
/// </summary>
/// <remarks>
/// A body other than one <c>return new Dictionary&lt;…&gt; { { "Name", n =&gt; … }, … };</c> is skipped without a diagnostic.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class FieldAssignmentGenerator : IIncrementalGenerator
{
    private const string InterfaceName = "global::Jellyfin.Sdk.Internal.IFieldAssignable";
    private const string ParseNodeName = "global::Microsoft.Kiota.Abstractions.Serialization.IParseNode";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is MethodDeclarationSyntax { Identifier.ValueText: "GetFieldDeserializers", ParameterList.Parameters.Count: 0 },
                static (syntaxContext, cancellationToken) => Generate((MethodDeclarationSyntax)syntaxContext.Node, cancellationToken))
            .Where(static model => model is not null);

        context.RegisterSourceOutput(models, static (output, model) => output.AddSource(model!.Value.HintName, SourceText.From(model.Value.Source, Encoding.UTF8)));
    }

    private static (string HintName, string Source)? Generate(MethodDeclarationSyntax method, CancellationToken cancellationToken)
    {
        if (method.Parent is not ClassDeclarationSyntax type
            || type.Parent is not BaseNamespaceDeclarationSyntax ns
            || !type.Modifiers.Any(SyntaxKind.PartialKeyword)
            || method.Body is not { Statements.Count: 1 } body
            || body.Statements[0] is not ReturnStatementSyntax { Expression: BaseObjectCreationExpressionSyntax { Initializer: { } initializer } })
        {
            return null;
        }

        var cases = new List<(string Name, string Parameter, IReadOnlyList<string> Statements)>();
        foreach (var expression in initializer.Expressions)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (expression is not InitializerExpressionSyntax { Expressions.Count: 2 } entry
                || entry.Expressions[0] is not LiteralExpressionSyntax key
                || entry.Expressions[1] is not SimpleLambdaExpressionSyntax lambda
                || !key.IsKind(SyntaxKind.StringLiteralExpression))
            {
                return null;
            }

            IReadOnlyList<string> statements = lambda switch
            {
                { Block: { } block } => block.Statements.Select(static s => s.ToString()).ToList(),
                { ExpressionBody: { } expressionBody } => [expressionBody + ";"],
                _ => [],
            };

            cases.Add((key.Token.ValueText, lambda.Parameter.Identifier.ValueText, statements));
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#pragma warning disable CS0618");
        if (type.SyntaxTree.GetRoot(cancellationToken) is CompilationUnitSyntax unit)
        {
            foreach (var usingDirective in unit.Usings)
            {
                source.AppendLine(usingDirective.ToString());
            }
        }

        source.Append("namespace ").AppendLine(ns.Name.ToString());
        source.AppendLine("{");
        source.Append("    partial class ").Append(type.Identifier.ValueText).Append(type.TypeParameterList).Append(" : ").AppendLine(InterfaceName);
        source.AppendLine("    {");
        source.Append("        bool ").Append(InterfaceName).Append(".TryAssignField(string name, ").Append(ParseNodeName).AppendLine(" parseNode)");
        source.AppendLine("        {");
        source.AppendLine("            switch (name)");
        source.AppendLine("            {");
        foreach (var (name, parameter, statements) in cases)
        {
            source.Append("                case ").Append(SymbolDisplay.FormatLiteral(name, quote: true)).AppendLine(":");
            source.AppendLine("                {");
            source.Append("                    var ").Append(parameter).AppendLine(" = parseNode;");
            foreach (var statement in statements)
            {
                source.Append("                    ").AppendLine(statement);
            }

            source.AppendLine("                    return true;");
            source.AppendLine("                }");
        }

        source.AppendLine("                default:");
        source.AppendLine("                    return false;");
        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine();
        source.Append("        bool ").Append(InterfaceName).AppendLine(".HasField(string name)");
        source.AppendLine("        {");
        source.AppendLine("            switch (name)");
        source.AppendLine("            {");
        foreach (var (name, _, _) in cases)
        {
            source.Append("                case ").Append(SymbolDisplay.FormatLiteral(name, quote: true)).AppendLine(":");
        }

        if (cases.Count > 0)
        {
            source.AppendLine("                    return true;");
        }

        source.AppendLine("                default:");
        source.AppendLine("                    return false;");
        source.AppendLine("            }");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");

        return ($"{ns.Name}.{type.Identifier.ValueText}.FieldAssignment.g.cs", source.ToString());
    }
}
